"""PTX (NVIDIA's virtual ISA) text: carve from memory and summarise."""

from __future__ import annotations

import re
from typing import Dict, List, Optional

VERSION_RE = re.compile(rb"\.version[ \t]+(\d+)\.(\d+)")
_TARGET_RE = re.compile(r"\.target[ \t]+([\w, ]+)")
_ADDR_RE = re.compile(r"\.address_size[ \t]+(\d+)")
_ENTRY_RE = re.compile(r"\.entry[ \t]+([A-Za-z_$%][\w$]*)\s*\(?")
_FUNC_RE = re.compile(r"\.func[ \t]+(?:\([^)]*\)[ \t]*)?([A-Za-z_$%][\w$]*)")
_GLOBAL_RE = re.compile(r"\.global[ \t]+(?:\.align[ \t]+\d+[ \t]+)?(?:\.\w+[ \t]+)+([A-Za-z_$%][\w$]*)")
_EXTERN_RE = re.compile(r"\.extern[ \t]+\.func[ \t]+(?:\([^)]*\)[ \t]*)?([A-Za-z_$%][\w$]*)")
_GENERATOR_RE = re.compile(r"//\s*(Generated by .*|Compiler Build ID: .*|Cuda compilation tools.*|Based on .*)")
_TEXT_BYTES = set(range(0x20, 0x7F)) | {0x09, 0x0A, 0x0D}


def carve(data: bytes, version_off: int, max_back: int = 4096, max_len: int = 64 << 20) -> Optional[tuple]:
    """Given the offset of a ``.version`` directive, return ``(start, end)`` of the
    surrounding PTX text (stops at the first non-text byte)."""
    start = version_off
    lo = max(0, version_off - max_back)
    while start > lo and data[start - 1] in _TEXT_BYTES:
        start -= 1
    end = version_off
    hi = min(len(data), version_off + max_len)
    while end < hi and data[end] in _TEXT_BYTES:
        end += 1
    if end - version_off < 16:
        return None
    return start, end


class PtxModule:
    def __init__(self, text: str):
        self.text = text
        m = re.search(r"\.version[ \t]+(\d+\.\d+)", text)
        self.version = m.group(1) if m else None
        m = _TARGET_RE.search(text)
        self.target = m.group(1).strip() if m else None
        m = _ADDR_RE.search(text)
        self.address_size = int(m.group(1)) if m else None
        self.entries: List[str] = _ENTRY_RE.findall(text)
        self.functions: List[str] = [f for f in _FUNC_RE.findall(text)]
        self.externs: List[str] = _EXTERN_RE.findall(text)
        self.globals: List[str] = _GLOBAL_RE.findall(text)
        self.generator: List[str] = _GENERATOR_RE.findall(text)

    @property
    def complete(self) -> bool:
        return self.version is not None and self.target is not None and self.text.rstrip().endswith("}")

    def summary(self) -> Dict[str, object]:
        return {"version": self.version, "target": self.target, "address_size": self.address_size,
                "entries": self.entries, "functions": self.functions, "externs": self.externs,
                "globals": self.globals, "generator": self.generator}


def parse(text) -> PtxModule:
    if isinstance(text, (bytes, bytearray)):
        text = bytes(text).decode("utf-8", "replace")
    return PtxModule(text)
